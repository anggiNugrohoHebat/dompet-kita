function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function parseTransactions(value: string | null): Transaction[] | null {
  if (value === null) return null;
  const parsed: unknown = JSON.parse(value);
  if (!Array.isArray(parsed)) throw new Error('Data transaksi tersimpan bukan berupa daftar.');

  return parsed.flatMap((item): Transaction[] => {
    if (
      !isRecord(item) ||
      typeof item.id !== 'string' ||
      typeof item.description !== 'string' ||
      typeof item.amount !== 'number' ||
      (item.type !== 'income' && item.type !== 'expense') ||
      typeof item.category !== 'string' ||
      typeof item.date !== 'string'
    ) {
      return [];
    }

    return [{
      id: item.id,
      description: item.description,
      amount: item.amount,
      type: item.type,
      category: legacyCategoryIds[item.category] ?? item.category,
      date: item.date,
      ...(item.isAutoGenerated === true ? { isAutoGenerated: true } : {}),
    }];
  });
}

function parseRecurringRules(value: string | null): RecurringRule[] | null {
  if (value === null) return null;
  const parsed: unknown = JSON.parse(value);
  if (!Array.isArray(parsed)) throw new Error('Data transaksi berulang tersimpan bukan berupa daftar.');

  return parsed.flatMap((item): RecurringRule[] => {
    if (
      !isRecord(item) ||
      typeof item.id !== 'string' ||
      typeof item.description !== 'string' ||
      typeof item.amount !== 'number' ||
      (item.type !== 'income' && item.type !== 'expense') ||
      typeof item.category !== 'string' ||
      (item.frequency !== 'daily' && item.frequency !== 'monthly')
    ) {
      return [];
    }

    const startDate = typeof item.startDate === 'string' ? item.startDate : getTodayISO();
    const nextDueDate = typeof item.nextDueDate === 'string' ? item.nextDueDate : startDate;

    return [{
      id: item.id,
      description: item.description,
      amount: item.amount,
      type: item.type,
      category: legacyCategoryIds[item.category] ?? item.category,
      frequency: item.frequency,
      nextDueDate,
      ...(typeof item.lastProcessedDate === 'string'
        ? { lastProcessedDate: item.lastProcessedDate }
        : typeof item.lastExecutedDate === 'string'
          ? { lastProcessedDate: item.lastExecutedDate }
          : {}),
      active: typeof item.active === 'boolean' ? item.active : item.isActive !== false,
    }];
  });
}

function parseDeletedIds(value: string | null): string[] {
  if (value === null) return [];
  const parsed: unknown = JSON.parse(value);
  if (!Array.isArray(parsed) || !parsed.every((id) => typeof id === 'string')) {
    throw new Error('Daftar penghapusan tersimpan tidak valid.');
  }
  return parsed;
}

function parseDriveBackup(content: string): DriveBackup {
  const parsed: unknown = JSON.parse(content);
  if (
    !isRecord(parsed) ||
    parsed.version !== 1 ||
    typeof parsed.updatedAt !== 'string' ||
    !Array.isArray(parsed.transactions) ||
    !Array.isArray(parsed.recurringRules) ||
    !Array.isArray(parsed.deletedTransactionIds) ||
    !parsed.deletedTransactionIds.every((id) => typeof id === 'string') ||
    !Array.isArray(parsed.deletedRecurringRuleIds) ||
    !parsed.deletedRecurringRuleIds.every((id) => typeof id === 'string')
  ) {
    throw new Error('Format file backup Dompet Kita di Google Drive tidak valid.');
  }

  const transactions = parseTransactions(JSON.stringify(parsed.transactions)) ?? [];
  const recurringRules = parseRecurringRules(JSON.stringify(parsed.recurringRules)) ?? [];
  if (
    transactions.length !== parsed.transactions.length ||
    recurringRules.length !== parsed.recurringRules.length
  ) {
    throw new Error('File backup berisi data yang tidak valid dan tidak dapat disinkronkan.');
  }

  return {
    version: 1,
    updatedAt: parsed.updatedAt,
    transactions,
    recurringRules,
    deletedTransactionIds: parsed.deletedTransactionIds,
    deletedRecurringRuleIds: parsed.deletedRecurringRuleIds,
  };
}

function mergeDriveBackups(local: DriveBackup, remote: DriveBackup): DriveBackup {
  const deletedTransactionIds = [...new Set([
    ...local.deletedTransactionIds,
    ...remote.deletedTransactionIds,
  ])];
  const deletedRecurringRuleIds = [...new Set([
    ...local.deletedRecurringRuleIds,
    ...remote.deletedRecurringRuleIds,
  ])];

  const transactionsById = new Map(local.transactions.map((transaction) => [transaction.id, transaction]));
  remote.transactions.forEach((transaction) => transactionsById.set(transaction.id, transaction));
  const recurringById = new Map(local.recurringRules.map((rule) => [rule.id, rule]));
  remote.recurringRules.forEach((rule) => recurringById.set(rule.id, rule));

  return {
    version: 1,
    updatedAt: new Date().toISOString(),
    transactions: [...transactionsById.values()].filter((item) => !deletedTransactionIds.includes(item.id)),
    recurringRules: [...recurringById.values()].filter((item) => !deletedRecurringRuleIds.includes(item.id)),
    deletedTransactionIds,
    deletedRecurringRuleIds,
  };
}

function dateFromISO(value: string): Date {
  return new Date(`${value}T00:00:00`);
}

function addFrequency(value: string, frequency: RecurringRule['frequency']): string {
  const date = dateFromISO(value);
  if (frequency === 'daily') {
    date.setDate(date.getDate() + 1);
  } else {
    const dayOfMonth = date.getDate();
    date.setDate(1);
    date.setMonth(date.getMonth() + 1);
    const lastDayOfMonth = new Date(date.getFullYear(), date.getMonth() + 1, 0).getDate();
    date.setDate(Math.min(dayOfMonth, lastDayOfMonth));
  }

  return [
    date.getFullYear(),
    String(date.getMonth() + 1).padStart(2, '0'),
    String(date.getDate()).padStart(2, '0'),
  ].join('-');
}

