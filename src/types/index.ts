// src/types/index.ts

export type TransactionType = 'income' | 'expense';

export type Category = {
  id: string;
  name: string;
  icon: string;
  color: string;
};

export type Transaction = {
  id: string;
  description: string;
  amount: number;
  type: TransactionType;
  category: string;
  date: string; // ISO string YYYY-MM-DD
  notes?: string;
  isRecurring?: boolean;
  recurringId?: string;
  isAutoGenerated?: boolean;
};

export type DriveRecurringRule = {
  id: string;
  description: string;
  amount: number;
  type: TransactionType;
  category: string;
  frequency: 'daily' | 'monthly';
  nextDueDate: string;
  lastProcessedDate?: string;
  active: boolean;
};

export type DriveBackup = {
  version: 1;
  updatedAt: string;
  transactions: Transaction[];
  recurringRules: DriveRecurringRule[];
  deletedTransactionIds: string[];
  deletedRecurringRuleIds: string[];
};

export type RecurringTransaction = {
  id: string;
  description: string;
  amount: number;
  type: TransactionType;
  category: string;
  frequency: 'daily' | 'monthly';
  startDate: string;
  lastExecutedDate?: string;
  nextDueDate: string;
  isActive: boolean;
};

export type DateFilter = 'all' | 'today' | 'month';